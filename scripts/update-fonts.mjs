import { readdir, writeFile } from 'node:fs/promises';
const directory = 'node_modules/@mathjax/mathjax-newcm-font/mjs/svg/dynamic';
const imports = (await readdir(directory)).filter(x => x.endsWith('.js')).sort().map(x =>
  `import '@mathjax/mathjax-newcm-font/mjs/svg/dynamic/${x}';`).join('\n');
await writeFile('packages/core/src/fonts.ts', `// Generated by scripts/update-fonts.mjs for the pinned local NewCM font.\n${imports}\n`);
